"""
Some questions have an exact, checkable answer sitting right in the index's
metadata — "how many images/tables/pages does this document have" — and an
LLM asked to count from a pile of retrieved chunks is not a reliable way to
get that number right. This module detects that class of question and
answers it directly by counting, bypassing the VLM (and retrieval scoring)
entirely for guaranteed correctness.

Returns None when the question doesn't match a countable pattern, so the
caller falls through to normal retrieval + generation.
"""
from app.indexing.vector_store import VectorStore
from app.models.schemas import AskResponse

COUNT_TRIGGERS = ("how many", "number of", "count of", "total number")
TARGET_KEYWORDS = {
    "image": ("image", "figure", "picture", "photo", "chart", "diagram"),
    "table": ("table",),
    "page": ("page",),
    "text": ("text", "paragraph"),
}


def _detect_targets(question_lower: str) -> list[str]:
    if not any(trigger in question_lower for trigger in COUNT_TRIGGERS):
        return []
    return [
        target
        for target, keywords in TARGET_KEYWORDS.items()
        if any(kw in question_lower for kw in keywords)
    ]


def try_structural_answer(
    question: str, store: VectorStore, document_id: str | None
) -> AskResponse | None:
    targets = _detect_targets(question.lower())
    if not targets:
        return None

    all_chunks = store.text_meta + store.image_meta
    if document_id:
        all_chunks = [c for c in all_chunks if c.document_id == document_id]

    if not all_chunks:
        return AskResponse(
            answer="No indexed content found for that document.",
            citations=[],
            retrieval_mode="none",
        )

    parts = []
    for target in targets:
        if target == "page":
            if document_id:
                page_count = max(c.page_number for c in all_chunks)
                parts.append(f"This document has {page_count} pages.")
            else:
                by_doc: dict[str, int] = {}
                for c in all_chunks:
                    by_doc[c.document_id] = max(by_doc.get(c.document_id, 0), c.page_number)
                total_pages = sum(by_doc.values())
                parts.append(
                    f"Across {len(by_doc)} indexed documents, there are "
                    f"{total_pages} pages total."
                )
            continue

        modality = target  # "image", "table", "text" match Chunk.modality directly
        matches = [c for c in all_chunks if c.modality == modality]
        pages = sorted({c.page_number for c in matches})
        page_list = ", ".join(str(p) for p in pages) if pages else "none"
        label = {"image": "image(s)", "table": "table(s)", "text": "text block(s)"}[modality]

        if document_id:
            parts.append(f"This document contains {len(matches)} {label}, on page(s): {page_list}.")
        else:
            parts.append(f"Across all indexed documents, there are {len(matches)} {label} total.")

    answer = " ".join(parts) + (
        "\n\n(Counted directly from the index — not generated by the language model, "
        "so this figure is exact.)"
    )

    return AskResponse(answer=answer, citations=[], retrieval_mode="none")